def build_marketplace(plugins: list[SourcePlugin]) -> dict[str, Any]:
    entries = []
    for plugin in plugins:
        entries.append(
            {
                "name": plugin.name,
                "source": {
                    "source": "local",
                    "path": f"./plugins/{plugin.name}",
                },
                "policy": {
                    "installation": "AVAILABLE",
                    "authentication": "ON_INSTALL",
                },
                "category": normalized_category(plugin.marketplace_entry),
            }
        )
    return {
        "name": "florianbuetow-codex-plugins",
        "interface": {"displayName": "Florian Buetow Codex Plugins"},
        "plugins": entries,
    }


def generate(source: Path, build_root: Path, source_label: str) -> dict[str, Any]:
    plugins, _ = discover_plugins(source)
    source_plugins_root = source / "plugins"
    output_plugins = build_root / "plugins"
    output_plugins.mkdir(parents=True, exist_ok=True)
    (output_plugins / MARKER).write_text(
        "Generated by scripts/sync_plugins.py; do not edit.\n", encoding="utf-8"
    )

    warnings: list[str] = []
    inventory: list[dict[str, Any]] = []
    total_skills = 0
    total_commands = 0
    total_agents = 0
    total_hook_adapters = 0
    total_skills_adapted = 0
    total_agents_converted = 0
    for plugin in plugins:
        destination = output_plugins / plugin.name
        destination.mkdir(parents=True)
        copied_files = copy_portable_content(plugin.directory, destination)
        skills_adapted = adapt_existing_skills(plugin, destination)
        converted_commands = convert_commands(plugin, destination)
        converted_agents = convert_agents(plugin, destination)
        agent_resources_adapted = adapt_agent_resources(plugin, destination)
        hook_adapters, hook_warnings = convert_hooks(plugin, destination)
        warnings.extend(hook_warnings)
        transform_plugin_readme(plugin, destination)
        portable, compatibility = plugin_manifests(plugin)
        write_json(destination / "plugin.json", portable)
        write_json(destination / ".codex-plugin" / "plugin.json", compatibility)

        skills = len(list((destination / "skills").glob("*/SKILL.md"))) if (destination / "skills").is_dir() else 0
        agents = len(list((destination / "agents").glob("*.md"))) if (destination / "agents").is_dir() else 0
        total_skills += skills
        total_commands += len(converted_commands)
        total_agents += agents
        total_agents_converted += len(converted_agents)
        total_hook_adapters += hook_adapters
        total_skills_adapted += skills_adapted
        inventory.append(
            {
                "name": plugin.name,
                "version": plugin.manifest.get("version"),
                "copiedFiles": copied_files,
                "skills": skills,
                "skillsAdapted": skills_adapted,
                "commandsConverted": converted_commands,
                "agentsConverted": converted_agents,
                "agentPromptsPreserved": agents,
                "agentPromptResourcesAdapted": agent_resources_adapted,
                "promptHooksConverted": hook_adapters,
            }
        )

    marketplace_root = build_root / ".agents" / "plugins"
    marketplace_root.mkdir(parents=True, exist_ok=True)
    (marketplace_root / MARKER).write_text(
        "Generated by scripts/sync_plugins.py; do not edit.\n", encoding="utf-8"
    )
    write_json(marketplace_root / "marketplace.json", build_marketplace(plugins))

    source_readme = (source / "README.md").read_text(encoding="utf-8")
    (build_root / "README.md").write_text(
        build_readme(source_readme, plugins), encoding="utf-8"
    )
    report = {
        "generatorVersion": GENERATOR_VERSION,
        "source": {
            "path": source_label,
            "revision": git_revision(source),
            "contentSha256": tree_digest(source_plugins_root),
        },
        "summary": {
            "plugins": len(plugins),
            "skills": total_skills,
            "skillsAdapted": total_skills_adapted,
            "commandsConverted": total_commands,
            "agentsConverted": total_agents_converted,
            "agentPromptsPreserved": total_agents,
            "promptHooksConverted": total_hook_adapters,
            "warnings": len(warnings),
        },
        "plugins": inventory,
        "warnings": sorted(warnings),
    }
    write_json(build_root / "generation-report.json", report)
    return report


def files_equal(left: Path, right: Path) -> bool:
    if left.is_symlink() or right.is_symlink():
        return False
    if not left.exists() or not right.exists():
        return left.exists() == right.exists()
    if left.is_file() != right.is_file() or left.is_dir() != right.is_dir():
        return False
    if left.is_file():
        return (
            left.read_bytes() == right.read_bytes()
            and stat.S_IMODE(left.stat().st_mode)
            == stat.S_IMODE(right.stat().st_mode)
        )
    left_entries = sorted(path.name for path in left.iterdir())
    right_entries = sorted(path.name for path in right.iterdir())
    if left_entries != right_entries:
        return False
    return all(files_equal(left / name, right / name) for name in left_entries)


def stale_paths(output: Path, generated: Path) -> list[str]:
    return [
        path.as_posix()
        for path in MANAGED_PATHS
        if not files_equal(output / path, generated / path)
    ]


def assert_managed_or_absent(path: Path) -> None:
    if path.is_symlink():
        raise SyncError(f"refusing to replace symlinked generated path {path}")
    if not path.exists():
        return
    if path.name == "plugins" and not path.is_dir():
        raise SyncError(f"refusing to replace wrong-type generated path {path}")
    if path.name in {"README.md", "generation-report.json"} and not path.is_file():
        raise SyncError(f"refusing to replace wrong-type generated path {path}")
    if path.is_dir() and not (path / MARKER).is_file():
        raise SyncError(
            f"refusing to replace unmarked directory {path}; expected {MARKER}"
        )
    if path.name == "README.md" and not path.read_text(
        encoding="utf-8"
    ).startswith(README_MARKER):
        raise SyncError(f"refusing to replace unmarked generated file {path}")
    if path.name == "generation-report.json":
        report = read_json(path)
        if "generatorVersion" not in report:
            raise SyncError(f"refusing to replace unmarked generated file {path}")


def remove_generated_path(path: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def validate_generated_tree(generated: Path) -> None:
    validator = Path(__file__).with_name("validate_generated.py")
    result = subprocess.run(
        [sys.executable, str(validator), "--root", str(generated)],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if result.returncode:
        detail = (result.stderr or result.stdout).strip()
        raise SyncError(f"generated output failed validation:\n{detail}")


def install_generated(output: Path, generated: Path) -> None:
    for relative in MANAGED_PATHS:
        assert_managed_or_absent(output / relative)

    transaction: list[tuple[Path, Path, Path, bool, bool]] = []
    for index, relative in enumerate(MANAGED_PATHS):
        destination = output / relative
        backup = destination.with_name(
            f".{destination.name}.sync-backup-{os.getpid()}-{index}"
        )
        if backup.exists():
            raise SyncError(f"temporary backup path already exists: {backup}")
        transaction.append(
            (generated / relative, destination, backup, destination.exists(), False)
        )

    try:
        for _, destination, backup, existed, _ in transaction:
            destination.parent.mkdir(parents=True, exist_ok=True)
            if existed:
                destination.rename(backup)
        for index, (source, destination, backup, existed, _) in enumerate(transaction):
            source.rename(destination)
            transaction[index] = (source, destination, backup, existed, True)
    except Exception:
        for _, destination, _, _, installed in reversed(transaction):
            if installed and destination.exists():
                remove_generated_path(destination)
        for _, destination, backup, existed, _ in reversed(transaction):
            if existed and backup.exists():
                backup.rename(destination)
        raise
    else:
        for _, _, backup, existed, _ in transaction:
            if existed:
                remove_generated_path(backup)


def main() -> int:
    args = parse_args()
    source = Path(args.source).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    validate_roots(source, output)
    source_before = git_snapshot(source)
    inputs_before = generation_inputs_digest(source)

    with tempfile.TemporaryDirectory(prefix=".codex-plugin-sync-", dir=output) as temp:
        generated = Path(temp)
        report = generate(source, generated, args.source)
        validate_generated_tree(generated)
        source_after = git_snapshot(source)
        inputs_after = generation_inputs_digest(source)
        if source_before != source_after or inputs_before != inputs_after:
            raise SyncError("source repository changed during generation; output not installed")
        if args.check:
            stale = stale_paths(output, generated)
            if stale:
                print("Generated output is stale:", file=sys.stderr)
                for path in stale:
                    print(f"- {path}", file=sys.stderr)
                print("Run `just update`.", file=sys.stderr)
                return 1
            print(
                f"Generated output is current: {report['summary']['plugins']} plugins, "
                f"{report['summary']['skills']} skills"
            )
            return 0
        install_generated(output, generated)

    summary = report["summary"]
    print(
        f"Generated {summary['plugins']} Codex plugins with {summary['skills']} skills "
        f"({summary['commandsConverted']} commands converted, "
        f"{summary['warnings']} documented warning(s))."
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SyncError as error:
        print(f"sync failed: {error}", file=sys.stderr)
        raise SystemExit(2)
