def codex_hook_command(prompt: str, event: str) -> str:
    encoded = base64.b64encode(prompt.encode("utf-8")).decode("ascii")
    program = (
        "import base64,json;"
        f"p=base64.b64decode('{encoded}').decode();"
        "print(json.dumps({'hookSpecificOutput':"
        f"{{'hookEventName':'{event}','additionalContext':p}}}}))"
    )
    return f'python3 -c "{program}"'


def convert_hooks(plugin: SourcePlugin, destination: Path) -> tuple[int, list[str]]:
    source_path = plugin.directory / "hooks" / "hooks.json"
    if not source_path.is_file():
        return 0, []
    config = read_json(source_path)
    hook_events = config.get("hooks")
    if not isinstance(hook_events, dict):
        raise SyncError(f"invalid hooks object in {source_path}")

    converted_count = 0
    warnings: list[str] = []
    output_events: dict[str, list[dict[str, Any]]] = {}
    supported_events = {
        "PreToolUse",
        "PermissionRequest",
        "PostToolUse",
        "PreCompact",
        "PostCompact",
        "UserPromptSubmit",
        "SubagentStop",
        "Stop",
        "Interrupt",
        "SessionStart",
        "SubagentStart",
        "SessionEnd",
    }
    for event, groups in hook_events.items():
        if event not in supported_events or not isinstance(groups, list):
            warnings.append(f"{plugin.name}: unsupported Claude hook event {event}")
            continue
        output_groups: list[dict[str, Any]] = []
        for group in groups:
            if not isinstance(group, dict):
                continue
            matcher = group.get("matcher")
            if matcher == "ExitPlanMode":
                warnings.append(
                    f"{plugin.name}: ExitPlanMode hook has no Codex lifecycle equivalent"
                )
                continue
            handlers = group.get("hooks")
            if not isinstance(handlers, list):
                continue
            output_handlers: list[dict[str, Any]] = []
            for handler in handlers:
                if not isinstance(handler, dict):
                    continue
                if handler.get("type") == "prompt" and isinstance(
                    handler.get("prompt"), str
                ):
                    if event not in PROMPT_CONTEXT_EVENTS:
                        warnings.append(
                            f"{plugin.name}: Codex {event} cannot faithfully adapt "
                            "a Claude prompt hook"
                        )
                        continue
                    output_handlers.append(
                        {
                            "type": "command",
                            "command": codex_hook_command(handler["prompt"], event),
                            "timeout": 10,
                            "statusMessage": "Loading plugin guidance",
                        }
                    )
                    converted_count += 1
                elif handler.get("type") in {"command", "mcp_tool"}:
                    output_handlers.append(handler)
                else:
                    warnings.append(
                        f"{plugin.name}: unsupported {event} hook handler "
                        f"{handler.get('type')!r}"
                    )
            if output_handlers:
                new_group: dict[str, Any] = {"hooks": output_handlers}
                if isinstance(matcher, str) and matcher:
                    new_group["matcher"] = matcher
                output_groups.append(new_group)
        if output_groups:
            output_events[event] = output_groups

    write_json(
        destination / "hooks" / "hooks.json",
        {
            "description": f"Codex lifecycle hooks generated from {plugin.name}.",
            "hooks": output_events,
        },
    )
    return converted_count, warnings


def codexize_invocations(text: str, plugin_name: str | None = None) -> str:
    text = re.sub(
        r"`/([a-z0-9][a-z0-9-]*(?::[a-z0-9][a-z0-9-]*)?)`",
        r"`$\1`",
        text,
    )
    text = text.replace(
        "https://docs.anthropic.com/en/docs/claude-code/hooks",
        "https://developers.openai.com/codex/hooks",
    )
    text = re.sub(
        r"(?m)^(\s*)/([a-z0-9][a-z0-9-]*(?::[a-z0-9][a-z0-9-]*)?)(?=\s|$)",
        r"\1$\2",
        text,
    )
    if plugin_name:
        text = text.replace(f"/{plugin_name}:", f"${plugin_name}:")
